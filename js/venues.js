export function getStadiumById(id) {
  return STADIUMS.find(s => s.id === Number(id)) || null;
}

export function getStadiumByName(name) {
  if (!name) return null;
  const lower = name.toLowerCase();
  return STADIUMS.find(s => s.name.toLowerCase() === lower
    || s.name.toLowerCase().includes(lower)
    || lower.includes(s.name.toLowerCase())
  ) || null;
}
